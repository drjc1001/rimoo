test('skillLine: title first, else split at the first comma, else the whole rule', () => {
  const r = merged().rules[0]!;
  assert.deepEqual(skillLine(r, 'zh'), { lead: '短句1。', rest: '結論先講，理由放後面。' });
  assert.deepEqual(skillLine({ ...r, title: null }, 'zh'), { lead: '結論先講。', rest: '理由放後面。' });
  assert.deepEqual(skillLine({ ...r, title: null, rule: 'Result first, then the reasons' }, 'en'), {
    lead: 'Result first.',
    rest: 'Then the reasons.',
  });
});

test('workstyle.json: every category as ranked keys, plus the full rule list', () => {
  const w = renderWorkstyle(input());
  assert.deepEqual(Object.keys(w), ['generatedAt', 'prompts', 'projects', ...CATEGORIES, 'rules']);
  assert.equal(w.prompts, 24045);
  assert.equal(w.projects, 61);
  assert.deepEqual(w.communication, ['key_1', 'key_3', 'key_7', 'key_12']);
  assert.deepEqual(w.testing, ['key_5', 'key_9']);
  assert.deepEqual(w.debugging, []);
  assert.equal(w.rules.length, 12);
  assert.deepEqual(w.rules[0], { key: 'key_1', category: 'communication', rule: '結論先講，理由放後面。', frequency: 40, chunks: 5, confidence: 'high' });
  assert.doesNotMatch(JSON.stringify(w), /引句/);
});

test('English rules: English wording around them, quotes in double quotes', () => {
  const m = merged();
  m.rules = m.rules.map((r, i) => ({ ...r, rule: `Rule number ${i + 1}, stated plainly`, title: null }));
  assert.equal(rulesLang(m.rules), 'en');
  const inp = { ...input(), merged: m };
  assert.match(formatTopRules(inp), /\n1\. Rule number 1, stated plainly \(in 5 chunks, 40 messages\)\n/);
  assert.match(renderReport(inp), / {5}- 2026-01-11 "引句1-1"\n/);
  assert.match(renderClaudeMd(inp), /\nThese rules were extracted from 24,045 prompts in my Claude Code history\.\n/);
  assert.match(renderSkillMd(inp), /description: "My working style .* 24,045 Claude Code prompts; strongest: key_1, key_2, key_3\. /);
  assert.match(renderSkillMd(inp), /\n1\. \*\*Rule number 1\.\*\* Stated plainly\.\n/);
});

test('writeExports: the four files, quotes only in report.md', async () => {
  const dir = await mkdtemp(path.join(tmpdir(), 'rimoo-export-'));
  try {
    const files = await writeExports(dir, input());
    assert.deepEqual(files, EXPORT_FILES.map((f) => path.join(dir, f)));
    const [report, claude, skill, workstyle] = await Promise.all(files.map((f) => readFile(f, 'utf8')));
    const quotes = merged().rules.flatMap((r) => r.evidence.slice(0, 3).map((e) => e.quote));
    for (const q of quotes) {
      assert.ok(report!.includes(q), q);
      for (const other of [claude!, skill!, workstyle!]) assert.ok(!other.includes(q), q);
    }
    assert.equal(JSON.parse(workstyle!).prompts, 24045);
  } finally {
    await rm(dir, { recursive: true, force: true });
  }
});
