let k = 0;
function rule(category: Category, text: string, confidence: Confidence, frequency: number, chunks: number, over: Partial<MergedRule> = {}): MergedRule {
  k++;
  return {
    key: `key_${k}`,
    category,
    title: `短句${k}`,
    rule: text,
    confidence,
    frequency,
    chunks,
    members: [k],
    evidence: [1, 2, 3, 4].map((i) => ({ id: k * 100 + i, ts: `2026-0${i}-1${i}T09:30`, quote: `引句${k}-${i}` })),
    trigger: null,
    ...over,
  };
}

/** Twelve ranked rules in Chinese, over five categories; debugging and architecture have none. */
function merged(): Merged {
  k = 0;
  const rules = [
    rule('communication', '結論先講，理由放後面。', 'high', 40, 5, { trigger: '看到長篇回報後' }),
    rule('planning', '動手前先給計畫。', 'high', 30, 4),
    rule('communication', '回報用條列編號。', 'medium', 3, 4),
    rule('ai_collaboration', '方向定了就一路做完。', 'medium', 2, 3),
    rule('testing', '有測試才算做完。', 'low', 20, 3),
    rule('implementation', '沿用既有元件。', 'high', 9, 2),
    rule('communication', '不要客套話。', 'high', 8, 2),
    rule('planning', '先開票再動工。', 'high', 7, 2),
    rule('testing', '先重現再修。', 'medium', 6, 1),
    rule('implementation', '後端先行。', 'high', 5, 1),
    rule('ai_collaboration', '卡住就換方法。', 'high', 4, 1, { title: null }),
    rule('communication', '字數上限是硬上限', 'high', 3, 1, { title: null }),
  ];
  return {
    generatedAt: '2026-09-27T01:00:00.000Z',
    findingsSha256: 'f'.repeat(64),
    chunksAnalyzed: 22,
    chunksTotal: 24,
    findings: 71,
    usage: { input: 0, cacheCreation: 0, cacheRead: 0, output: 0, thinking: 0, total: 0 },
    costUsd: 0,
    durationMs: 0,
    dropped: { unknown: 0, duplicate: 0, groups: 0 },
    rules,
  };
}

const input = (): ExportInput => ({ merged: merged(), stats: { prompts: 24045, projects: 61 }, now: new Date(2026, 8, 27, 10) });

test('formatTopRules: the §8 lines, chunks analyzed, ten rules with where they were seen', () => {
  const text = formatTopRules(input());
  const lines = text.split('\n');
  assert.equal(lines[0], 'Rimoo analyzed 24,045 prompts across 61 projects.');
  assert.equal(lines[1], '22 of 24 chunks analyzed.');
  assert.equal(lines[3], 'Your strongest working patterns:');
  assert.equal(lines[5], '1. 結論先講，理由放後面。（出現於 5 段、40 則）');
  assert.equal(lines[14], '10. 後端先行。（出現於 1 段、5 則）');
  assert.equal(text.match(/^\d+\. /gm)!.length, 10);
  assert.doesNotMatch(text, /卡住就換方法/);
  const none = { ...input(), merged: { ...merged(), rules: [] } };
  assert.match(formatTopRules(none), /No working pattern was found\.\n$/);
});

test('report.md: summary on top, every category, confidence, trigger only when known, three dated quotes', () => {
  const md = renderReport(input());
  assert.match(md, /^# Rimoo report\n\nRimoo analyzed 24,045 prompts across 61 projects\.\n22 of 24 chunks analyzed\.\n\nYour strongest working patterns:\n\n1\. 結論先講/);
  for (const title of ['Communication', 'Planning', 'Implementation', 'Testing', 'Debugging', 'Architecture', 'AI collaboration']) {
    assert.match(md, new RegExp(`\\n## ${title}\\n`));
  }
  assert.match(md, /## Debugging\n\n（沒有找到）\n/);
  assert.match(
    md,
    /## Communication\n\n1\. \*\*結論先講，理由放後面。\*\*（出現於 5 段、40 則）\n {3}- Confidence: high\n {3}- Trigger: 看到長篇回報後\n {3}- Quotes:\n {5}- 2026-01-11「引句1-1」\n {5}- 2026-02-12「引句1-2」\n {5}- 2026-03-13「引句1-3」\n\n2\. \*\*回報用條列編號。\*\*（出現於 4 段、3 則）\n {3}- Confidence: medium\n {3}- Quotes:/,
  );
  assert.doesNotMatch(md, /引句1-4/); // three quotes at most
  // Every rule is in, the low one too.
  for (const r of merged().rules) assert.ok(md.includes(r.rule));
});

test('CLAUDE.md: title with the date, rules only if high or medium said 3+ times, no quotes', () => {
  const md = renderClaudeMd(input());
  assert.match(md, /^# How I work with AI \(generated by Rimoo on 2026-09-27\)\n\n以下是從我 24,045 則 Claude Code 歷史訊息抽出來的工作規則。\n\n## Communication\n\n- 結論先講，理由放後面。\n- 回報用條列編號。\n- 不要客套話。\n- 字數上限是硬上限\n\n## Planning\n/);
  assert.doesNotMatch(md, /方向定了就一路做完/); // medium, said twice
  assert.doesNotMatch(md, /有測試才算做完/); // low
  assert.match(md, /- 先重現再修。/); // medium, six times
  assert.doesNotMatch(md, /## Debugging|## Architecture/); // nothing in them
  assert.doesNotMatch(md, /引句|「/);
  assert.deepEqual(
    merged().rules.filter(isPortable).map((r) => r.rule).filter((t) => !md.includes(t)),
    [],
  );
});

